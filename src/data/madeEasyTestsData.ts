export function getMadeEasyStats(gateSubjects?: Subject[]): MadeEasyStats {
  const tests = getAllMadeEasyTests(gateSubjects);
  const fullMocksCount = tests.filter((t) => t.type === "Full Syllabus Mock").length;
  const topicTestsCount = tests.filter((t) => t.type === "Topic Wise Test").length;
  const totalQuestions = tests.reduce((acc, t) => acc + (t.questions ? t.questions.length : t.totalQuestions), 0);
  const totalMarks = tests.reduce((acc, t) => acc + t.totalMarks, 0);
  const subjectKeys = Array.from(new Set(tests.map((t) => t.subjectKey)));

  return {
    totalTests: tests.length,
    fullMocksCount,
    topicTestsCount,
    totalQuestions,
    totalMarks,
    uniqueSubjectsCount: subjectKeys.length,
    subjectKeys,
  };
}
